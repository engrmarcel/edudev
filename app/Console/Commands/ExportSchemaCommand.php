<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Process;

/**
 * Regenerates database/sql/edudev.sql from the CURRENT migrated database.
 *
 * Output = full schema (all tables) + reference data from an explicit
 * allow-list of tables (migrations, roles, permissions). It never dumps
 * user, session, payment, AI conversation or other personal data.
 *
 * This is NOT a backup tool. See docs/BACKUP_AND_RESTORE.md.
 */
class ExportSchemaCommand extends Command
{
    protected $signature = 'edudev:export-schema
        {--path=database/sql/edudev.sql : Output file relative to the project root}
        {--mysqldump= : Path to the mysqldump binary (defaults to MYSQLDUMP_PATH or "mysqldump")}';

    protected $description = 'Export the schema and safe reference data to database/sql/edudev.sql';

    /** Tables whose rows are safe reference data. Keep this list short. */
    private const REFERENCE_TABLES = [
        'migrations',
        'permissions',
        'roles',
        'role_has_permissions',
    ];

    public function handle(): int
    {
        $connection = config('database.default');
        $cfg = config("database.connections.{$connection}");

        if (! in_array($cfg['driver'] ?? null, ['mysql', 'mariadb'], true)) {
            $this->error("The default connection [{$connection}] is not MySQL/MariaDB.");

            return self::FAILURE;
        }

        $binary = $this->option('mysqldump') ?: env('MYSQLDUMP_PATH', 'mysqldump');
        $out = base_path($this->option('path'));
        File::ensureDirectoryExists(dirname($out));

        $base = [
            $binary,
            '--host='.$cfg['host'],
            '--port='.$cfg['port'],
            '--user='.$cfg['username'],
            '--single-transaction',
            '--skip-comments',
            '--skip-dump-date',
            '--default-character-set=utf8mb4',
        ];

        // Pass the password through the environment, not the command line,
        // so it does not appear in process listings.
        $env = ['MYSQL_PWD' => (string) ($cfg['password'] ?? '')];

        $schema = Process::env($env)->run([...$base, '--no-data', '--routines', '--triggers', $cfg['database']]);
        if (! $schema->successful()) {
            $this->error('Schema export failed: '.trim($schema->errorOutput()));

            return self::FAILURE;
        }

        $existing = collect(DB::select('SHOW TABLES'))->map(fn ($row) => array_values((array) $row)[0])->all();
        $refTables = array_values(array_intersect(self::REFERENCE_TABLES, $existing));

        $data = '';
        if ($refTables !== []) {
            $dump = Process::env($env)->run([...$base, '--no-create-info', '--skip-triggers', '--complete-insert', $cfg['database'], ...$refTables]);
            if (! $dump->successful()) {
                $this->error('Reference data export failed: '.trim($dump->errorOutput()));

                return self::FAILURE;
            }
            $data = $dump->output();
        }

        $header = implode("\n", [
            '-- -----------------------------------------------------------------',
            '-- EduDEV database export (schema + reference data)',
            '-- Generated by: php artisan edudev:export-schema',
            '-- Source of truth: database/migrations. Regenerate after every migration change.',
            '-- Reference data tables: '.implode(', ', $refTables),
            '-- Contains NO user accounts, passwords, tokens, payments or student content.',
            '-- -----------------------------------------------------------------',
            '',
            'SET FOREIGN_KEY_CHECKS=0;',
            '',
        ]);

        // mysqldump embeds the database name in some statements; strip the
        // definer so the file imports cleanly under any MySQL user.
        $body = preg_replace('/ DEFINER=`[^`]+`@`[^`]+`/', '', $schema->output()."\n".$data);

        File::put($out, $header.$body."\nSET FOREIGN_KEY_CHECKS=1;\n");

        $this->info('Exported '.count($existing).' tables to '.$this->option('path'));

        return self::SUCCESS;
    }
}
